// NewBoilerplateOptions creates a new BoilerplateOptions struct
func NewBoilerplateOptions(
	templateFolder,
	outputFolder string,
	vars map[string]any,
	terragruntOpts *options.TerragruntOptions,
) *boilerplateoptions.BoilerplateOptions {
	return &boilerplateoptions.BoilerplateOptions{
		TemplateFolder:          templateFolder,
		OutputFolder:            outputFolder,
		OnMissingKey:            boilerplateoptions.DefaultMissingKeyAction,
		OnMissingConfig:         boilerplateoptions.DefaultMissingConfigAction,
		Vars:                    vars,
		ShellCommandAnswers:     map[string]bool{},
		NoShell:                 terragruntOpts.NoShell,
		NoHooks:                 terragruntOpts.NoHooks,
		NonInteractive:          terragruntOpts.NonInteractive,
		DisableDependencyPrompt: terragruntOpts.NoDependencyPrompt,
		// Manifest must be true so ProcessTemplateWithContext records each
		// dependency's generated files. Without it, result.Dependencies has
		// empty Files and GeneratedFiles() would omit them.
		Manifest: true,
	}
}

// Plan captures the state of a scaffold preparation: the source module has
// been downloaded, its variables parsed, and the boilerplate template
// located. Generate finishes the render, optionally injecting user-supplied
// HCL fragments via the values argument, and Cleanup removes the temporary
// directories Prepare allocated. Callers must invoke Cleanup exactly once,
// typically via defer.
type Plan struct {
	logger            log.Logger
	Required          []*config.ParsedVariable
	Optional          []*config.ParsedVariable
	tempDirs          []string
	vars              map[string]any
	boilerplateDir    string
	originalModuleURL string
	resolvedModuleURL string
	outputDir         string
	sourceDir         string
	values            component.ValuesReferences
	generatedFiles    []string
	kind              component.Kind
}

// FormFields returns what a user is asked to fill in before this plan is
// generated: the variables of a module or template, or the `values.*`
// references a unit or stack makes. Empty when the source asks for nothing.
func (p *Plan) FormFields() []form.Field {
	if p.kind.IsCopyable() {
		return form.FieldsFromValuesReferences(p.values)
	}

	return form.FieldsFromParsedVariables(p.Required, p.Optional)
}

// Kind returns what [Prepare] found at the source. [Plan.Generate] renders a
// module and copies a unit or stack.
func (p *Plan) Kind() component.Kind {
	return p.kind
}

// SourceDir returns the directory [Prepare] downloaded the source into.
func (p *Plan) SourceDir() string {
	return p.sourceDir
}

// TemplateDir returns the boilerplate template [Plan.Generate] renders a
// module with. It is empty for a unit or stack.
func (p *Plan) TemplateDir() string {
	return p.boilerplateDir
}

// Cleanup removes the temporary directories allocated during Prepare.
// Safe to call more than once; subsequent calls are no-ops.
func (p *Plan) Cleanup(fsys vfs.FS) {
	for _, dir := range p.tempDirs {
		if err := fsys.RemoveAll(dir); err != nil {
			p.logger.Warnf("Failed to clean up dir %s: %v", dir, err)
		}
	}

	p.tempDirs = nil
}

// GeneratedFiles returns the files the last [Plan.Generate] call rendered,
// as sorted, deduplicated paths relative to the output directory.
//
// Returns nil before Generate runs, and for a unit or stack, which Generate
// copies without recording the files.
func (p *Plan) GeneratedFiles() []string {
	return p.generatedFiles
}

// Prepare downloads the source module and template, parses the module's
// variable blocks, and returns a [Plan] ready for rendering. The caller is
// responsible for invoking [Plan.Cleanup] (typically via defer) once it has
// either rendered the result via [Plan.Generate] or decided to abandon the
// work.
func Prepare(
	ctx context.Context,
	l log.Logger,
	v *venv.Venv,
	opts *options.TerragruntOptions,
	moduleURL, templateURL string,
) (*Plan, error) {
	// Apply catalog configuration settings, with CLI flags taking precedence
	applyCatalogConfigToScaffold(ctx, l, v, opts)

	outputDir := OutputDir(opts)

	if err := warnWhenNotEmpty(l, v.FS, outputDir); err != nil {
		return nil, err
	}

	if moduleURL == "" {
		return nil, NoModuleURLPassed{}
	}

	moduleURL = tf.RewriteLegacyGCSPublicSource(ctx, l, moduleURL, opts.StrictControls)
	templateURL = tf.RewriteLegacyGCSPublicSource(ctx, l, templateURL, opts.StrictControls)

	// create temporary directory where to download module
	tempDir, err := vfs.MkdirTemp(v.FS, v.Platform.TempDir(), "scaffold")
	if err != nil {
		return nil, err
	}

	plan := &Plan{
		logger:    l,
		outputDir: outputDir,
		sourceDir: tempDir,
		tempDirs:  []string{tempDir},
	}

	// On any error after this point, clean up the temp dir we just created
	// so a partial Prepare doesn't leak.
	success := false

	defer func() {
		if !success {
			plan.Cleanup(v.FS)
		}
	}()

	varFiles := make([]string, len(opts.ScaffoldVarFiles))
	for i, varFile := range opts.ScaffoldVarFiles {
		varFiles[i] = underWorkingDir(opts.WorkingDir, varFile)
	}

	vars, err := variables.ParseVars(opts.ScaffoldVars, varFiles)
	if err != nil {
		return nil, err
	}

	// parse module url (transforms for go-getter download)
	resolvedURL, err := parseModuleURL(ctx, l, v, opts, vars, moduleURL)
	if err != nil {
		return nil, err
	}

	plan.resolvedModuleURL = resolvedURL

	plan.originalModuleURL, err = unitSource(moduleURL, resolvedURL, opts.WorkingDir, outputDir)
	if err != nil {
		return nil, err
	}

	l.Debugf("Scaffolding a new Terragrunt module %s to %s", resolvedURL, outputDir)

	if err := telemetry.TelemeterFromContext(ctx).
		Collect(ctx, l, "scaffold_get_module", map[string]any{
			"module_url": resolvedURL,
		}, func(ctx context.Context, l log.Logger) error {
			if getErr := fetchScaffoldSource(ctx, l, v, tempDir, resolvedURL); getErr != nil {
				return fmt.Errorf("downloading scaffold module from %s: %w", resolvedURL, getErr)
			}

			return nil
		}); err != nil {
		return nil, err
	}

	markers, err := component.Inspect(v.FS, tempDir)
	if err != nil {
		return nil, err
	}

	// A unit or a stack is already a Terragrunt configuration, so there is
	// nothing to generate from it: rendering the module template would point
	// terraform.source at a directory holding no .tf files at all. Its own
	// files are what the user wants, which is what the catalog user interface
	// gives them, so Generate copies them instead.
	if kind, ok := markers.CopyKind(); ok {
		warnUnusedScaffoldInputs(l, opts, templateURL, kind)

		values, err := component.Values(v.FS, kind, tempDir)
		if err != nil {
			return nil, err
		}

		plan.kind = kind
		plan.values = values
		success = true

		return plan, nil
	}

	// extract variables from downloaded module
	requiredVariables, optionalVariables, err := parseVariables(l, v, opts, tempDir)
	if err != nil {
		return nil, err
	}

	plan.Required = requiredVariables
	plan.Optional = optionalVariables

	l.Debugf(
		"Parsed %d required variables and %d optional variables",
		len(requiredVariables),
		len(optionalVariables),
	)

	// prepare boilerplate files to render Terragrunt files
	boilerplateDir, err := prepareBoilerplateFiles(ctx, l, v, opts, templateURL, tempDir)
	if err != nil {
		return nil, err
	}

	plan.boilerplateDir = boilerplateDir
	plan.vars = vars

	success = true

	return plan, nil
}

// OutputDir returns the directory scaffold writes into: --output-folder taken
// from the working directory when relative, or the working directory itself
// when the flag is not set.
func OutputDir(opts *options.TerragruntOptions) string {
	if opts.ScaffoldOutputFolder == "" {
		return opts.WorkingDir
	}

	return underWorkingDir(opts.WorkingDir, opts.ScaffoldOutputFolder)
}

// underWorkingDir returns path cleaned when absolute, and joined under
// workingDir otherwise.
func underWorkingDir(workingDir, path string) string {
	if filepath.IsAbs(path) {
		return filepath.Clean(path)
	}

	return filepath.Join(workingDir, path)
}

// warnWhenNotEmpty logs a warning when dir holds anything. A dir that does not
// exist yet is empty: boilerplate creates it.
func warnWhenNotEmpty(l log.Logger, fsys vfs.FS, dir string) error {
	empty, err := vfs.IsDirectoryEmpty(fsys, dir)
	if errors.Is(err, fs.ErrNotExist) {
		return nil
	}

	if err != nil {
		return err
	}

	if !empty {
		l.Warnf("The output directory %s is not empty.", dir)
	}

	return nil
}

// unitSource returns the source the generated unit points at. A relative local
// module path is read against the working directory when downloading, but a
// unit reads its source against its own directory, so the path is rewritten
// relative to outputDir. Every other source is kept as the user wrote it.
func unitSource(moduleURL, resolvedURL, workingDir, outputDir string) (string, error) {
	if !isRelativeLocalSource(moduleURL, resolvedURL) {
		return moduleURL, nil
	}

	base, query := splitURLQuery(moduleURL)
	base, subDir := getter.SourceDirSubdir(base)

	rel, err := filepath.Rel(outputDir, filepath.Join(workingDir, base))
	if err != nil {
		return "", err
	}

	source := filepath.ToSlash(rel)
	if source != "." && source != ".." && !strings.HasPrefix(source, "../") {
		source = "./" + source
	}

	if subDir != "" {
		source += "//" + subDir
	}

	if query != "" {
		source += "?" + query
	}

	return source, nil
}

// isRelativeLocalSource reports whether moduleURL names a local path relative
// to the working directory: it is not absolute, carries no scheme or forced
// getter, and the detector chain resolved it to a file URL rather than a
// forge shorthand.
func isRelativeLocalSource(moduleURL, resolvedURL string) bool {
	if filepath.IsAbs(moduleURL) {
		return false
	}

	if u, err := url.Parse(moduleURL); err == nil && u.Scheme != "" {
		return false
	}

	resolved, err := url.Parse(resolvedURL)

	return err == nil && tf.IsLocalSource(resolved)
}

// Generate renders the prepared scaffold into the output directory. When
// values is non-nil, each entry replaces the matching parsed variable's
// UserValue, so the template emits a real HCL assignment instead of the
// `# TODO: fill in value` placeholder. Variables not present in values
// fall through to the placeholder line.
func (p *Plan) Generate(
	ctx context.Context,
	l log.Logger,
	v *venv.Venv,
	opts *options.TerragruntOptions,
	values map[string]string,
) error {
	// The zero kind is a module, so a plan whose source was never classified
	// as copyable renders, which is every plan Prepare built before units and
	// stacks could be scaffolded by copying.
	if p.kind.IsCopyable() {
		return p.copyComponent(l, v, values)
	}

	applyUserValues(p.Required, values)
	applyUserValues(p.Optional, values)

	// add additional variables
	p.vars["requiredVariables"] = p.Required
	p.vars["optionalVariables"] = p.Optional

	// Build sourceUrl from the original URL with the ref that parseModuleURL resolved.
	p.vars["sourceUrl"] = BuildSourceURL(p.originalModuleURL, p.resolvedModuleURL, p.vars)

	// Only set these if the `vars` map doesn't already have them set
	setVarDefault(
		l,
		p.vars,
		enableRootInclude,
		!opts.ScaffoldNoIncludeRoot,
		shared.NoIncludeRootFlagName,
	)
	setVarDefault(l, p.vars, rootFileName, opts.ScaffoldRootFileName, shared.RootFileNameFlagName)

	if err := p.checkRootFile(ctx, l, v, opts); err != nil {
		return err
	}

	l.Debugf("Running boilerplate generation to %s", p.outputDir)
	boilerplateOpts := NewBoilerplateOptions(p.boilerplateDir, p.outputDir, p.vars, opts)

	emptyDep := &variables.Dependency{}

	result, err := templates.ProcessTemplateWithContext(
		ctx,
		l,
		boilerplateOpts,
		boilerplateOpts,
		emptyDep,
	)
	if err != nil {
		return err
	}

	depFiles, err := collectDependencyFiles(p.outputDir, result.Dependencies, 0)
	if err != nil {
		return err
	}

	allFiles := slices.Concat(result.GeneratedFiles, depFiles)

	for i, f := range allFiles {
		allFiles[i] = filepath.Clean(f)
	}

	allFiles = slices.Compact(slices.Sorted(slices.Values(allFiles)))

	p.generatedFiles = allFiles

	l.Debugf("Running fmt on generated code %s", p.outputDir)

	if err := format.RunForFiles(ctx, l, v, opts, p.outputDir, allFiles); err != nil {
		return err
	}

	l.Debug("Scaffolding completed")

	return nil
}

// copyComponent scaffolds a unit or stack into the output directory, alongside
// a terragrunt.values.hcl for the `values.*` references its configuration
// makes. It is the same work the catalog user interface does, so a component
// lands identically whichever one the user reaches for.
func (p *Plan) copyComponent(l log.Logger, v *venv.Venv, values map[string]string) error {
	paths := component.Paths{Root: p.sourceDir, Src: p.sourceDir, Dst: p.outputDir}

	result, err := component.Scaffold(v.FS, p.kind, paths, values)
	if err != nil {
		return err
	}

	l.Infof("Scaffolded %s into %s", p.kind, p.outputDir)

	valuesPath := filepath.Join(p.outputDir, component.ValuesFileName)

	if result.ValuesWritten {
		l.Infof("Generated %s; fill in each TODO before running Terragrunt", valuesPath)
	}

	if result.ValuesSkipped {
		l.Warnf(
			"%s already exists and was left untouched; check that it sets %s",
			valuesPath,
			strings.Join(result.References.AllNames(), ", "),
		)
	}

	return nil
}

// warnUnusedScaffoldInputs reports the inputs that only apply when generating
// a configuration, so a user who passed them does not go looking for their
// effect in a component that was copied verbatim.
func warnUnusedScaffoldInputs(
	l log.Logger,
	opts *options.TerragruntOptions,
	templateURL string,
	kind component.Kind,
) {
	if templateURL != "" {
		l.Warnf("A %s is copied as it is written, so the template argument is ignored.", kind)
	}

	if len(opts.ScaffoldVars) > 0 || len(opts.ScaffoldVarFiles) > 0 {
		l.Warnf(
			"A %s is copied as it is written, so --%s and --%s are ignored."+
				" Set its values in %s instead.",
			kind,
			VarFlagName,
			VarFileFlagName,
			component.ValuesFileName,
		)
	}
}

// setVarDefault writes value to vars[key] when the key is absent; if
// it's already set, it logs a warning that flagName will be ignored.
func setVarDefault(l log.Logger, vars map[string]any, key string, value any, flagName string) {
	if _, found := vars[key]; found {
		l.Warnf(
			"The %s variable is already set in the var flag(s). The --%s flag will be ignored.",
			key,
			flagName,
		)

		return
	}

	vars[key] = value
}

// applyUserValues copies non-empty entries from values onto the matching
// ParsedVariable.UserValue, so the template emits the supplied HCL fragment
// instead of the TODO placeholder line. Empty values are treated as
// "not supplied" and leave the existing UserValue untouched.
func applyUserValues(vars []*config.ParsedVariable, values map[string]string) {
	if len(values) == 0 {
		return
	}

	for _, v := range vars {
		val, ok := values[v.Name]
		if !ok || val == "" {
			continue
		}

		v.UserValue = val
	}
}

// Run downloads the source module, discovers its variables, and renders a
// terragrunt.hcl with `# TODO: fill in value` placeholders for every input.
// It is the non-interactive entry point used by the CLI scaffold command and
// the catalog TUI's `S` (placeholder) keybind.
func Run(
	ctx context.Context,
	l log.Logger,
	v *venv.Venv,
	opts *options.TerragruntOptions,
	moduleURL, templateURL string,
) error {
	plan, err := Prepare(ctx, l, v, opts, moduleURL, templateURL)
	if err != nil {
		return err
	}

	defer plan.Cleanup(v.FS)

	return plan.Generate(ctx, l, v, opts, nil)
}

// BuildSourceURL returns the original module URL with the ref query param
// from the resolved URL appended, so the scaffolded source preserves the
// user's original URL format while including the resolved version tag.
//
// When vars sets SourceUrlType to git-ssh, the resolved URL is returned
// instead so that the scaffolded source carries the Git/SSH rewrite that
// rewriteModuleURL applied.
func BuildSourceURL(originalURL, resolvedURL string, vars map[string]any) string {
	if value, found := vars[sourceURLTypeVar]; found &&
		fmt.Sprintf("%s", value) == sourceURLTypeGit {
		return resolvedURL
	}

	refVal := ExtractQueryParam(resolvedURL, refParam)
	if refVal == "" {
		return originalURL
	}

	base, rawQuery := splitURLQuery(originalURL)

	params, err := url.ParseQuery(rawQuery)
	if err != nil || params.Has(refParam) {
		return originalURL
	}

	params.Set(refParam, refVal)

	return base + "?" + params.Encode()
}

// ExtractQueryParam extracts a query parameter value from a URL string.
// It splits on the last "?" to find the query portion, avoiding issues with
// go-getter prefixes (e.g. "git::") that confuse url.Parse.
func ExtractQueryParam(rawURL, param string) string {
	_, rawQuery := splitURLQuery(rawURL)

	params, err := url.ParseQuery(rawQuery)
	if err != nil {
		return ""
	}

	return params.Get(param)
}

// splitURLQuery splits a raw URL at the last "?" into the base and query
// string. Go-getter URLs may contain "::" prefixes that prevent full URL
// parsing, but the query string is always after the final "?".
func splitURLQuery(rawURL string) (string, string) {
	base, query, _ := strings.CutLast(rawURL, "?")

	return base, query
}

// applyCatalogConfigToScaffold applies catalog configuration settings to scaffold options.
// CLI flags take precedence over config file settings.
func applyCatalogConfigToScaffold(
	ctx context.Context,
	l log.Logger,
	v *venv.Venv,
	opts *options.TerragruntOptions,
) {
	pctx := configbridge.NewParsingContext(opts)

	catalogCfg, err := config.ReadCatalogConfig(ctx, l, v, pctx)
	if err != nil {
		// Don't fail if catalog config can't be read - it's optional
		l.Debugf("Could not read catalog config for scaffold: %v", err)
		return
	}

	if catalogCfg == nil {
		return
	}

	// Apply config settings only if CLI flags weren't explicitly set
	// Since both NoShell and NoHooks default to false, we apply the config value
	// only if it's true (enabling the restriction)
	if catalogCfg.NoShell != nil && *catalogCfg.NoShell && !opts.NoShell {
		l.Debugf("Applying catalog config: no_shell = true")

		opts.NoShell = true
	}

	if catalogCfg.NoHooks != nil && *catalogCfg.NoHooks && !opts.NoHooks {
		l.Debugf("Applying catalog config: no_hooks = true")

		opts.NoHooks = true
	}
}

// generateDefaultTemplate - write default template to provided dir
func generateDefaultTemplate(fsys vfs.FS, boilerplateDir string) (string, error) {
	const ownerWriteGlobalReadPerms = 0o644
	if err := vfs.WriteFile(
		fsys,
		filepath.Join(
			boilerplateDir,
			config.DefaultTerragruntConfigPath,
		),
		[]byte(DefaultTerragruntTemplate),
		ownerWriteGlobalReadPerms,
	); err != nil {
		return "", err
	}

	if err := vfs.WriteFile(
		fsys,
		filepath.Join(
			boilerplateDir,
			"boilerplate.yml",
		),
		[]byte(DefaultBoilerplateConfig),
		ownerWriteGlobalReadPerms,
	); err != nil {
		return "", err
	}

	return boilerplateDir, nil
}

// downloadTemplate - parse URL, download files, and handle subfolders
func downloadTemplate(
	ctx context.Context,
	l log.Logger,
	v *venv.Venv,
	opts *options.TerragruntOptions,
	templateURL,
	tempDir string,
) (string, error) {
	parsedTemplateURL, err := tf.ToSourceURL(templateURL, tempDir)
	if err != nil {
		return "", err
	}

	// Split the processed URL to get the base URL and subfolder
	baseURL, subFolder, err := tf.SplitSourceURL(l, v.FS, parsedTemplateURL)
	if err != nil {
		return "", err
	}

	if baseURL.Scheme == "" || baseURL.Scheme == "file" {
		baseURL.Path = filepath.ToSlash(strings.TrimSuffix(baseURL.Path, "/"))
	}

	baseURL, err = rewriteTemplateURL(ctx, l, v, opts, baseURL)
	if err != nil {
		return "", err
	}

	templateDir, err := vfs.MkdirTemp(v.FS, tempDir, "template")
	if err != nil {
		return "", err
	}

	l.Debugf("Downloading template from %s into %s", baseURL.String(), templateDir)
	// Downloading baseURL to support boilerplate dependencies and partials.
	// Go-getter discards all but specified folder if one is provided.
	if err := telemetry.TelemeterFromContext(ctx).
		Collect(ctx, l, "scaffold_get_template", map[string]any{
			"template_url": baseURL.String(),
		}, func(ctx context.Context, l log.Logger) error {
			if getErr := fetchScaffoldSource(
				ctx,
				l,
				v,
				templateDir,
				baseURL.String(),
			); getErr != nil {
				return fmt.Errorf(
					"downloading scaffold template from %s: %w",
					baseURL.String(),
					getErr,
				)
			}

			return nil
		}); err != nil {
		return "", err
	}

	// Add subfolder to templateDir if provided, as scaffold needs path to boilerplate.yml file
	if subFolder != "" {
		subFolder = strings.TrimPrefix(subFolder, "/")
		templateDir = filepath.Join(templateDir, subFolder)
		// Verify that subfolder exists
		if _, err := v.FS.Stat(templateDir); errors.Is(err, fs.ErrNotExist) {
			return "", fmt.Errorf(
				"subfolder \"//%s\" not found in downloaded template from %s",
				subFolder,
				templateURL,
			)
		}
	}

	return templateDir, nil
}

// fetchScaffoldSource downloads the module or template at src into dst.
func fetchScaffoldSource(ctx context.Context, l log.Logger, v *venv.Venv, dst, src string) error {
	fileCopy := getter.NewFileCopyGetter(v.FS).
		WithLogger(l).
		WithIncludeInCopy(".*", "**/.*")

	if _, err := getter.GetAny(ctx, l, v, dst, src, getter.WithFileCopy(fileCopy)); err != nil {
		return err
	}

	return removeSourceManifests(v.FS, dst)
}

// removeSourceManifests deletes every source manifest under dir. Copying a
// local source writes one into each directory it creates. A file of the same
// name fetched by any other getter goes too: the name is Terragrunt's, and a
// manifest committed by an earlier scaffold must not spread to another tree.
func removeSourceManifests(fsys vfs.FS, dir string) error {
	return vfs.WalkDir(fsys, dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}

		if d.IsDir() || d.Name() != getter.SourceManifestName {
			return nil
		}

		return fsys.Remove(path)
	})
}

// prepareBoilerplateFiles - prepare boilerplate files from provided template, tf module, or (custom) default template
func prepareBoilerplateFiles(
	ctx context.Context,
	l log.Logger,
	v *venv.Venv,
	opts *options.TerragruntOptions,
	templateURL,
	tempDir string,
) (string, error) {
	boilerplateDir := filepath.Join(tempDir, util.DefaultBoilerplateDir)

	// process template url if it was passed. This overrides the .boilerplate folder in the OpenTofu/Terraform module
	if templateURL != "" {
		// process template url if it was passed
		tempTemplateDir, err := downloadTemplate(ctx, l, v, opts, templateURL, tempDir)
		if err != nil {
			return "", err
		}

		boilerplateDir = tempTemplateDir
	}

	// if boilerplate dir is not found, create one with default template
	if !vfs.IsDir(v.FS, boilerplateDir) {
		pctx := configbridge.NewParsingContext(opts)

		config, err := config.ReadCatalogConfig(ctx, l, v, pctx)
		if err != nil {
			return "", err
		}

		// use defaultTemplateURL if defined in config, otherwise use basic default template
		if config != nil && config.DefaultTemplate != "" {
			// process template url if available
			tempTemplateDir, err := downloadTemplate(
				ctx,
				l,
				v,
				opts,
				config.DefaultTemplate,
				tempDir,
			)
			if err != nil {
				return "", err
			}

			boilerplateDir = tempTemplateDir
		} else {
			defaultTempDir, err := vfs.MkdirTemp(v.FS, tempDir, "boilerplate")
			if err != nil {
				return "", err
			}

			boilerplateDir = defaultTempDir

			boilerplateDir, err = generateDefaultTemplate(v.FS, boilerplateDir)
			if err != nil {
				return "", err
			}
		}
	}

	return boilerplateDir, nil
}

// parseVariables - parse variables from tf files.
func parseVariables(
	l log.Logger,
	v *venv.Venv,
	opts *options.TerragruntOptions,
	moduleDir string,
) ([]*config.ParsedVariable, []*config.ParsedVariable, error) {
	inputs, err := config.ParseVariables(l, v, opts.StrictControls, moduleDir)
	if err != nil {
		return nil, nil, err
	}

	// separate variables that require value and with default value
	var (
		requiredVariables []*config.ParsedVariable
		optionalVariables []*config.ParsedVariable
	)

	for _, value := range inputs {
		if value.DefaultValue == "" {
			requiredVariables = append(requiredVariables, value)
		} else {
			optionalVariables = append(optionalVariables, value)
		}
	}

	return requiredVariables, optionalVariables, nil
}

// parseModuleURL - parse module url and rewrite it if required
func parseModuleURL(
	ctx context.Context,
	l log.Logger,
	v *venv.Venv,
	opts *options.TerragruntOptions,
	vars map[string]any,
	moduleURL string,
) (string, error) {
	parsedModuleURL, err := tf.ToSourceURL(moduleURL, opts.WorkingDir)
	if err != nil {
		return "", err
	}

	moduleURL = parsedModuleURL.String()

	// rewrite module url, if required
	parsedModuleURL, err = rewriteModuleURL(l, opts, vars, moduleURL)
	if err != nil {
		return "", err
	}

	// add ref to module url, if required
	parsedModuleURL, err = addRefToModuleURL(ctx, l, v, opts, parsedModuleURL, vars)
	if err != nil {
		return "", err
	}

	// regenerate module url with all changes
	return parsedModuleURL.String(), nil
}

// rewriteModuleURL rewrites module url to git ssh if required
// github.com/gruntwork-io/terragrunt.git//test/fixtures/inputs =>
// git::https://github.com/gruntwork-io/terragrunt.git//test/fixtures/inputs
func rewriteModuleURL(
	l log.Logger,
	opts *options.TerragruntOptions,
	vars map[string]any,
	moduleURL string,
) (*url.URL, error) {
	updatedModuleURL := moduleURL

	sourceURLType := sourceURLTypeHTTPS
	if value, found := vars[sourceURLTypeVar]; found {
		sourceURLType = fmt.Sprintf("%s", value)
	}

	// expand module url
	parsedValue, err := parseURL(l, moduleURL)
	if err != nil {
		l.Warnf("Failed to parse module url %s", moduleURL)

		parsedModuleURL, err := tf.ToSourceURL(updatedModuleURL, opts.WorkingDir)
		if err != nil {
			return nil, err
		}

		return parsedModuleURL, nil
	}
	// try to rewrite module url if is https and is requested to be git
	// git::https://github.com/gruntwork-io/terragrunt.git//test/fixtures/inputs =>
	// git::ssh://git@github.com/gruntwork-io/terragrunt.git//test/fixtures/inputs
	if parsedValue.scheme == "https" && sourceURLType == sourceURLTypeGit {
		gitUser := sourceGitSSHUser
		if value, found := vars[sourceGitSSHUserVar]; found {
			gitUser = fmt.Sprintf("%s", value)
		}

		path := strings.TrimPrefix(parsedValue.path, "/")
		updatedModuleURL = fmt.Sprintf("%s@%s:%s", gitUser, parsedValue.host, path)
	}

	// persist changes in url.URL
	parsedModuleURL, err := tf.ToSourceURL(updatedModuleURL, opts.WorkingDir)
	if err != nil {
		return nil, err
	}

	return parsedModuleURL, nil
}

// rewriteTemplateURL rewrites template url with reference to tag
// github.com/denis256/terragrunt-tests.git//scaffold/base-template =>
// github.com/denis256/terragrunt-tests.git//scaffold/base-template?ref=v0.53.8
func rewriteTemplateURL(
	ctx context.Context,
	l log.Logger,
	v *venv.Venv,
	opts *options.TerragruntOptions,
	parsedTemplateURL *url.URL,
) (*url.URL, error) {
	var (
		updatedTemplateURL = parsedTemplateURL
		templateParams     = updatedTemplateURL.Query()
	)

	ref := templateParams.Get(refParam)
	if ref == "" {
		rootSourceURL, _, err := tf.SplitSourceURL(l, v.FS, updatedTemplateURL)
		if err != nil {
			return nil, err
		}

		if rootSourceURL.Scheme == "" || rootSourceURL.Scheme == "file" {
			l.Debugf("Skipping git tag lookup for local template path: %s", rootSourceURL)
			return updatedTemplateURL, nil
		}

		tag, err := shell.GitLastReleaseTag(ctx, l, v, opts.WorkingDir, rootSourceURL)
		if err != nil || tag == "" {
			l.Warnf(
				"Failed to find last release tag for URL %s, so will not add a ref param to the URL",
				rootSourceURL,
			)
		} else {
			templateParams.Add(refParam, tag)
			updatedTemplateURL.RawQuery = templateParams.Encode()
		}
	}

	return updatedTemplateURL, nil
}

// addRefToModuleURL adds ref to module url if is passed through variables or find it from git tags
func addRefToModuleURL(
	ctx context.Context,
	l log.Logger,
	v *venv.Venv,
	opts *options.TerragruntOptions,
	parsedModuleURL *url.URL,
	vars map[string]any,
) (*url.URL, error) {
	moduleURL := parsedModuleURL
	// append ref to source url, if is passed through variables or find it from git tags
	params := moduleURL.Query()

	refReplacement, refVarPassed := vars[refVar]
	if refVarPassed {
		params.Set(refParam, fmt.Sprintf("%s", refReplacement))
		moduleURL.RawQuery = params.Encode()
	}

	ref := params.Get(refParam)
	if ref == "" {
		// if ref is not passed, find last release tag
		// git::https://github.com/gruntwork-io/terragrunt.git//test/fixtures/inputs =>
		// git::https://github.com/gruntwork-io/terragrunt.git//test/fixtures/inputs?ref=v0.53.8
		rootSourceURL, _, err := tf.SplitSourceURL(l, v.FS, moduleURL)
		if err != nil {
			return nil, err
		}

		if rootSourceURL.Scheme == "" || rootSourceURL.Scheme == "file" {
			l.Debugf("Skipping git tag lookup for local module path: %s", rootSourceURL)
			return moduleURL, nil
		}

		tag, err := shell.GitLastReleaseTag(ctx, l, v, opts.WorkingDir, rootSourceURL)
		if err != nil || tag == "" {
			l.Warnf("Failed to find last release tag for %s", rootSourceURL)
		} else {
			params.Add(refParam, tag)
			moduleURL.RawQuery = params.Encode()
		}
	}

	return moduleURL, nil
}

// parseURL parses module url to scheme, host and path
func parseURL(l log.Logger, moduleURL string) (*parsedURL, error) {
	matches := moduleURLRegex.FindStringSubmatch(moduleURL)
	if len(matches) != moduleURLParts {
		l.Warnf("Failed to parse url %s", moduleURL)
		return nil, failedToParseURLError{}
	}

	return &parsedURL{
		scheme: matches[1],
		host:   matches[2],
		path:   matches[3],
	}, nil
}

type parsedURL struct {
	scheme string
	host   string
	path   string
}

const maxDependencyDepth = 100

// collectDependencyFiles recursively collects file paths from all boilerplate
// dependencies and their nested sub-dependencies up to maxDependencyDepth.
// Each path is returned relative to outputDir, the generation root.
func collectDependencyFiles(
	outputDir string,
	deps []manifest.ManifestDependency,
	depth int,
) ([]string, error) {
	if depth >= maxDependencyDepth {
		return nil, MaxDependencyDepthExceededError{}
	}

	var files []string

	for i := range deps {
		for _, f := range deps[i].Files {
			files = append(files, dependencyFilePath(outputDir, deps[i].OutputFolder, f.Path))
		}

		subFiles, err := collectDependencyFiles(outputDir, deps[i].Dependencies, depth+1)
		if err != nil {
			return nil, err
		}

		files = append(files, subFiles...)
	}

	return files, nil
}

// dependencyFilePath returns file relative to outputDir. Boilerplate records
// file relative to the dependency's output folder, which it has already
// resolved under outputDir.
func dependencyFilePath(outputDir, outputFolder, file string) string {
	p := file
	if outputFolder != "" {
		p = filepath.Join(outputFolder, file)
	}

	if filepath.IsAbs(p) && outputDir != "" {
		if rel, err := filepath.Rel(outputDir, p); err == nil {
			parentPrefix := ".." + string(filepath.Separator)
			if rel != ".." && !strings.HasPrefix(rel, parentPrefix) {
				return rel
			}
		}
	}

	return p
}

// checkRootFile looks up the root file the generated include names, applying root-terragrunt-hcl.
func (p *Plan) checkRootFile(ctx context.Context, l log.Logger, v *venv.Venv, opts *options.TerragruntOptions) error {
	include, err := rootIncludeEnabled(p.vars[enableRootInclude])
	if err != nil {
		return fmt.Errorf("parsing %s: %w", enableRootInclude, err)
	}

	if !include {
		return nil
	}

	name := fmt.Sprint(p.vars[rootFileName])

	pctx := config.NewParsingContext(config.WithStrictControls(opts.StrictControls))
	pctx.TerragruntConfigPath = filepath.Join(p.outputDir, config.DefaultTerragruntConfigPath)
	pctx.MaxFoldersToCheck = opts.MaxFoldersToCheck

	_, err = config.FindInParentFolders(ctx, l, v, pctx, []string{name})
	if errors.As(err, new(config.ParentFileNotFoundError)) {
		return nil
	}

	return err
}

// rootIncludeEnabled reads EnableRootInclude the way boilerplate converts it to a bool.
func rootIncludeEnabled(value any) (bool, error) {
	switch v := value.(type) {
	case nil:
		return false, nil
	case bool:
		return v, nil
	case string:
		return strconv.ParseBool(v)
	}

	return true, nil
}

type MaxDependencyDepthExceededError struct{}

func (err MaxDependencyDepthExceededError) Error() string {
	return fmt.Sprintf(
		"dependency depth limit of %d exceeded, possible circular dependencies",
		maxDependencyDepth,
	)
}

